// Rewrites eslint.known-violations.mjs from what the code does now.
//
//   npm run lint:baseline
//
// Lints the whole tree with every rule of eslint.config.mjs and no known
// violations, then records, for each rule, the files that break it. For the
// size rules (complexity, max-lines-per-function, max-params) it names the
// functions, so the list says which functions a phase still has to split.
//
// Run it after a change that fixes violations, and read the diff: it should
// only remove lines. A line it adds is a new violation, which belongs fixed
// in the change rather than recorded here.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ESLint } from 'eslint';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The rules whose entries name functions rather than count violations. */
const SIZE_RULES = new Set(['complexity', 'max-lines-per-function', 'max-params', '@typescript-eslint/max-params']);

/** The function a size message is about, by name, or its kind when it has none. */
function functionName(message) {
  const named = /^(?:Async )?(?:Function|Method|Arrow function|Generator function|Async function|Async method|Async arrow function)?\s*'([^']+)'/i.exec(message)
    ?? /(?:function|method) '([^']+)'/i.exec(message);
  if (named) {
    return named[1];
  }
  const kind = /^((?:Async )?(?:arrow function|function|method))/i.exec(message);
  return `(${kind ? kind[1].toLowerCase() : 'function'})`;
}

process.env.DECKARD_LINT_ALL = '1';
const eslint = new ESLint({ cwd: ROOT });
const results = await eslint.lintFiles(['.']);

const known = {};
const unrecordable = [];
for (const result of results) {
  const file = path.relative(ROOT, result.filePath);
  for (const message of result.messages) {
    if (!message.ruleId) {
      unrecordable.push(`${file}:${message.line} ${message.message}`);
      continue;
    }
    known[message.ruleId] ??= {};
    const entry = known[message.ruleId];
    if (SIZE_RULES.has(message.ruleId)) {
      entry[file] = [...new Set([...(entry[file] ?? []), functionName(message.message)])].sort();
    } else {
      entry[file] = (entry[file] ?? 0) + 1;
    }
  }
}
if (unrecordable.length) {
  console.error('These cannot be recorded as known and must be fixed:\n' + unrecordable.join('\n'));
  process.exit(1);
}

const sorted = Object.fromEntries(Object.keys(known).sort().map((rule) => [
  rule,
  Object.fromEntries(Object.keys(known[rule]).sort().map((file) => [file, known[rule][file]])),
]));
const body = JSON.stringify(sorted, null, 2).replace(/"([a-z@/-]+)":/g, (all, key) => (/^[a-z]+$/.test(key) ? `${key}:` : all));
writeFileSync(path.join(ROOT, 'eslint.known-violations.mjs'), `// The lint violations recorded as known: for each rule, the files that broke it
// when it arrived, with the functions still over the limit for the size rules
// and a count for the rest. eslint.config.mjs turns each rule off for its
// files. Generated by \`npm run lint:baseline\`; a change that fixes a
// violation regenerates it, and the list only shrinks.
export default ${body};
`);
const total = Object.values(sorted).reduce((sum, files) => sum + Object.keys(files).length, 0);
console.log(`${Object.keys(sorted).length} rules, ${total} file entries recorded.`);
